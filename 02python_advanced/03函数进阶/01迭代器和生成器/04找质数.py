# 找质数（该数的因数只能是 1 和它本身）
# 使用生成器语法 无限质数生成器
# 生成器好处：用到第几个才算出第几个，不会一次性把无数个质数都算出来占内存
def generator_func():
    # 想体现生成器必须有 yield
    yield 2 # 2 是最小的质数，先直接扔出去（下面循环只从奇数开始，会漏掉 2）
    i = 3
    while True: # 死循环----> 质数有无数个 只要一直造一直有
        # 判断 i 是不是质数：拿 2 ~ i-1 的每个数去除 i
        # for...else 结构：for 循环正常跑完（一次都没 break）才执行 else；
        # 如果中途被 break 打断，就直接跳过 else
        # 关键：else 属于整个 for 循环，不是属于里面某一次 if，所以是"全部试完再下结论"
        for j in range(2, i):
            if i % j == 0: # 能被整除 说明还有别的因数 则不是质数
                break      # 既然确定不是质数，后面不用再试了，直接跳出
            # 举例 i=5：会依次用 2、3、4 去除 5，都没整除，循环自然走完
            # 然后才会到下面 else 里把 5 yield 出去
        else: # 循环正常结束、没被 break 打断 说明 2~i-1 全都除不尽 则就是质数
            yield i
        i += 2 # 除了 2 以外偶数都不是质数，所以每次 +2 只检查奇数即可
            # 注意：千万不能写成 if...else 放在 for 里面！
            # 因为 if...else 每一轮循环都会执行一次 else：
            # 比如 i=9，j=2 时 9%2!=0 就会立刻执行 else 把 9 yield 出去（错误）
            # 而 9 真正的因数 3 还没轮到判断。这就是为什么必须用 for...else。
if __name__ == '__main__':
    gen = generator_func() # 创建一个生成器对象
    for item in gen: # 不断调用 next(gen) 触发 yield 交出一个质数
        if item >= 100: # 一旦 item 大于等于 100 就退出 即生成器随之停止，不再浪费资源
            break
        print(item, end=" ")



# ============================================================
# property 详解
# ============================================================
# 核心作用：把「方法调用」伪装成「属性访问」。
# 写法上你还是用 person.age 这种最简单的属性语法，
# 但读取 / 赋值 / 删除时，Python 会自动去调用你预先写好的
# getter / setter / deleter 三个函数。
#
# 为什么要这么做？
#   1. 加校验：赋值时能拦截非法数据（比如负数年龄）
#   2. 保接口：外部调用代码永远是 person.age，不会因为
#      内部加了逻辑而需要改成 person.set_age(30)
#   3. 只读控制：只写 getter 不写 setter，属性就变成只读
# ============================================================


# ---------- 反面教材（被注释掉的普通写法） ----------
# class Person:
#     def __init__(self, age):
#         self.age = age       # age 就是一个赤裸裸的普通属性
#
# person = Person(66)
# print(person.age)            # 读得到
# person.age = 30              # 想怎么写就怎么写
# print(person.age)
# person.age = -60             # 负数也塞得进去，没人拦
# 问题：没有任何校验，谁都能把 age 改成不合法的值。


class Person:
    def __init__(self, age):
        # _age 前面加下划线 = 「受保护属性」
        # 注意：这只是给程序员看的约定标签，意思是“内部使用，别直接碰”。
        # Python 并不会真的拦截，person._age = 999 依然能改。
        # 真正对外的入口是后面的 age（没有下划线）。
        self._age = age

    # --------------------------------------------------------
    # 第一步：定义读取时干什么（getter）
    # --------------------------------------------------------
    @property
    # @property 做的事情：把下面这个 age 函数包装成一个
    # 名叫 age 的 property 对象。
    # 从此 person.age（读）不再拿到函数本身，而是自动
    # 调用这个 age() 函数并返回它的结果。
    # 重要：如果只写 @property 而不写 setter，这个属性就是「只读」的，
    #       一旦尝试 person.age = 30 就会抛 AttributeError。
    def age(self):
        return self._age

    # --------------------------------------------------------
    # 第二步：定义写入时干什么（setter）
    # --------------------------------------------------------
    @age.setter
    # age.setter 是第一步那个 property 对象自带的方法。
    # 用它可以把下面这个新函数注册成「写入时的逻辑」。
    # 函数名必须还叫 age（否则 property 找不到，会出错）。
    def age(self, value):
        # 这里就是校验逻辑，拦截非法赋值
        if value < 0:
            raise ValueError("年龄不能为负数")
        # 校验通过才真正存进内部属性
        self._age = value

    # --------------------------------------------------------
    # 第三步：定义删除时干什么（deleter）
    # --------------------------------------------------------
    @age.deleter
    # 当外部执行 del person.age 时，就会触发下面这个函数。
    def age(self):
        del self._age


# ============================================================
# 执行流程演示
# ============================================================
person = Person(20)
# 注意：实例化时 __init__ 里写的是 self._age = age，
# 不是 self.age = age。
# 如果写成 self.age = age，会触发 setter，也走一遍校验。

print(person.age)
# 读取：表面上像读属性，实际上 Python 偷偷调用了 age() 这个
# getter 函数，返回 self._age，所以打印 20。

person.age = 30
# 赋值：表面上像改属性，实际上 Python 偷偷调用了 age.setter，
# 也就是第二段那个 age(self, value) 函数。
# 30 不小于 0，校验通过，_age 被改成 30。

print(person.age)  # 打印 30

person.age = -60
# 赋值：又触发 setter。这次 -60 < 0，直接 raise ValueError。
# 所以程序会在这里抛异常中断，下面是执行不到的。
# 这正说明了 property 的价值：非法数据根本进不了对象内部。

print(person.age)

'''
集合set 集合是一个无序的不重复的序列---自动过滤重复元素
    元素与元素之间用逗号分隔

'''
# 创建集合 方法一
set1 = {1,2,3,4,5,5,5,5,3} # 输出后不会有重复的数字
print(set1, type(set1))


# 创建集合方法2 构造器
set2 = set([1,2,3,4,5,5,5,5,5])
print(set2, type(set2))

# 获取集合中元素的个数--这个个数是去掉重复内容之后的个数
print(len(set1))

# print(set1[0]) 如果用下标取值会报错，因为集合是没有顺序的。所以无法通过下标去访问元素

# 但是可以通过循环遍历去取值
for x in set1:
    print(x, end=" ")










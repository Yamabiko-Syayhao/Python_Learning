# 注释 给程序员自己看的 就是给代码写一个解释 不会输出内容
# 第一种注释 单行注释

"""
    第二种注释
    多行注释
    在python中本质上是一个字符串，而不是真正的注释，如果他没有被赋值给任何一个变量，解释器会创建它但是立即丢弃，从而达到一个“注释”的作用
"""
'''
    单引号
    双引号
    都是多行注释
'''

"""
    ctrl + /  注释或者取消注释
    ctrl + A  全选
    ctrl + X  剪切
    ctrl + C  复制
    ctrl + V  粘贴
    ctrl + D  快速复制当前行
    ctrl + Z  撤销
"""

# 控制台输出一句话  两行 两句话
print("今天周一")

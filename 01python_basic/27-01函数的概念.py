# 函数：如果有一段代码可以重复使用，就可以定义为一个函数，减少代码量，提高代码的可读性
"""
    函数分类
        系统内置函数
            print()  sum()   min()  max()....
        自定义函数
            自己写的函数

    定义函数
        def 函数名():
            函数体

    使用/调用函数
        函数名()
"""

# 定义函数
def say_hello():
    print("hello")

# 调用函数
say_hello()
say_hello()
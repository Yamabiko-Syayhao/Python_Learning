'''
4.*args 可变位置参数，把多的数变成元组包括进去——> 元组
**kwargs 可变关键字参数，接受任意多个关键字参数，把多的参数变成字典包括进去，要指定键值对——> 字典
'''
def fn2(a, b, *args, c = 100, **kwargs):
    print(a, b)
    print(args)
    print(c)
    print(kwargs)

"""
    函数的参数：函数名后边括号里边的变量就是参数，目的是当函数在调用的时候，可以对用户传进来的值进行操作
    传参/传值：用户在调用函数的时候给变量进行赋值 这个过程

    定义函数
    def 函数名(形参1,形参2...形参n):
        函数体

    调用函数
    函数名(实参1,实参2...实参n)

    形参：形式上的参数，相当于定义了一个没有赋值的变量
    实参：实际传进去的参数，就是要给形参赋的具体的值
"""

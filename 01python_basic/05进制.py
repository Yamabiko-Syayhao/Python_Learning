# 常见进制 二进制 八进制 十进制 十六进制
# 电脑只识别二进制，所有的图片文件都是以二进制的形式存在电脑里边

# 十进制
a1 = 1999

# 二进制 以0b开头  bin() 数字转为二进制
a2 = 0b110
print(bin(a1))

# 八进制  以0o开头  oct() 数字转为八进制
a3 = 0o1232
print(oct(a1))

# 十六进制 以0x开头  hex() 数字转为十六进制
a4 = 0x29a
print(hex(a1))

# 转为十进制的函数 int()
print(int(a2))

# 科学计数法  小数点往后推几位
a5 = 123e-6
print(a5)
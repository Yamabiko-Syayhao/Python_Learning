# 引导用户输入三个数字
a = int(input("请输入第一个数字："))
b = int(input("请输入第二个数字："))
c = int(input("请输入第三个数字："))

# 需求： 正序 从小到大
# 思路：想比较三个数的大小 可以两两相比，左右两个数字相比，如果左边的比右边的大，那么就交换位置

# 第一步 a和b相比较 如果a大于b  那么交换位置
if a > b:
    # 寻找一个第三方 交换位置
    # d = a
    # a = b
    # b = d
    a, b = b, a
# 第二步 再把b和c相比较
if b > c:
    b, c = c, b
# 最后一步 再次确认一下a和b谁大
if a > b:
    a, b = b, a

print(a,b,c)


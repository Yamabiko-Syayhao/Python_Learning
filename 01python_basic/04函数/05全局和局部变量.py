"""
    局部变量 在函数内部定义的变量就是局部变量，只能在函数内部使用
    全局变量 在函数外面定义的变量，函数内部和外部都能使用的变量
"""
def fn1():
    b = "hello"
    print(f"函数内部的b--{b}")

fn1()
# 报错  因为b这个变量是定义在函数内部的变量 局部变量 所以函数外面不能用
# print(f"函数外部的b--{b}")

# 全局变量 在函数外部定义的变量
a = 999
def fn2():
    print(a,"函数内部")
fn2()
print(a,"函数外部")

c = 55
def fn3():
    # global关键字 将函数内部的局部变量转为全局变量
    global c
    c = "world"
    print(c,"函数内部的c")

print(c,"函数外部的c")
fn3()
# world  因为fn3函数被调用了，所以将里边的局部变量转为全局变量 并且把外部原来的值覆盖了
print(c,"函数外部的c")
# 浮点数精度问题   计算机内部是用二进制来存储所有数据的，我们平常使用的十进制小数在转换成二进制的时候 无法被精确表示，计算机的内存是有限的，只能“截断”并存储他的相似值
print(0.1+0.2,"www")
# 值不一样 是因为计算顺序不同导致的四舍五入误差累积不同
print(0.1+0.2+0.3)
print(0.3+0.1+0.2)
print(0.3+0.2+0.1)

# 如何解决
# 1.先转为整数再计算
# 0.1===》1  0.2===》2  0.3===》3   每一个都乘以了10，整数相加的和再除以10
# 2.round(数字，保留的小数位数) 对数字做四舍五入  第二个参数如果不写 默认取整数
print(round(0.3+0.1+0.2,1))

"""
    什么是变量？可以理解为一个存东西的小盒子，将来把东西存到这个盒子中的过程叫赋值
    定义变量
        变量名 = 值
    变量名的命名规则：
        变量名必须是字母或者下划线开头，不能用特殊字符和数字开头
        大小写区分明确，a和A是两个变量
        禁止用关键字和保留字（系统已经用过的已经存在的）作为变量名 比如if  class  def  for等等
        建议尽量见名知意  两个单词之间可以用下划线链接   比如说学生名  student_name
"""

# 现在就是定义了一个名字叫str的盒子  将这句话放到了盒子里边  后期如果我们想用这句话  直接喊这个盒子名即可
str = "李子豪得了一种病，运动过敏症"
# 使用的时候直接去拿盒子名称
print(str)
print("李子豪得了一种病，运动过敏症")

# 给变量重新赋值
str = "想变瘦必须运动不过敏"
print(str)

# 多变量赋值  多个变量一起赋值不同的数据  等号左右两边的数量要一致
aa,bb,cc = 1,222,3
print(aa,bb,cc)

# 链式赋值  多个变量赋值同一个值
# e f g三个值是相等的

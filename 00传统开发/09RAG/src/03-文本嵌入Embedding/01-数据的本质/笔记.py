"""
1 灰度图片：
    灰度图片就是黑白图
    本质 = 是一个二维矩阵(矩形的长方形) 每个元素对应像素点的灰度值(0-255  0是纯黑色 255是纯白色)
    灰度图 类似于 一张表格，每格一个"亮度数字"（0~255）
2 彩色图片
    本质 = 是一个三维矩阵，0是黑色，255是白色，存在一个0-255中间值，将这三个叠在一起合成的就是彩色
    RGB - 红绿蓝三原色
    一共有255*255*255 = 1600w颜色  正常来说应该是256的三次方 1677w
    彩色图 = 三张亮度表格叠一起（红/绿/蓝），每个像素三个数

dpi 像素点 一张图无限放大 会出现一个一个像素点，这些点就是 dpi
像素点越多 图片越清楚
视频由多个图片组成

3 英文数据的本质
    本质：先转换为字符--->对应词汇表索引--->转换为固定维度的向量，最终是一个二维矩阵
    把英文拆成一个一个的单词，每个单词对应编号，把编号转换成固定长度的数字（这串数字叫词向量），最后成为一个二维表格
    文字 → 拆词 → 查编号 → 每个词换成一串数字 → 排成表格。
4 中文数据的本质
    跟英语差不多，就是把一句话拆成一个字或者一个词，转为高纬度的向量，最终是一个二维矩阵

核心：不管图片还是文字，计算机都先把它变成"排好队的数字表格"，然后才能计算。
"""